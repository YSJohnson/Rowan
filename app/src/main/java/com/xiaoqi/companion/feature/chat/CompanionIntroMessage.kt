package com.xiaoqi.companion.feature.chat

/**
 * 首次进入对话时 Rowan 主动发的开场白。
 *
 * 用固定文案而不是让模型生成：这是"还没有任何上下文"的时刻，调模型既慢又不可控，
 * 而这句开场白要传达的只有两件事 —— 邀请用户自我介绍，以及"你说过的我会记住"。
 * 第二点必须提前讲清楚，否则用户不知道这个 App 的长期记忆是默认开启的。
 */
internal const val COMPANION_INTRO_MESSAGE: String =
    "嗨，我是 Rowan。我们还没正式聊过 —— 先让我认识一下你吧？\n\n" +
        "随便说点什么都行：你怎么称呼、最近在忙什么、今天心情怎么样。" +
        "你告诉我的事我会记住，以后就不用重复说了。"
